const db = openDb();
let addedQ = 0; let addedT = 0;

for (const [numStr, data] of Object.entries(BANK)) {
  const lesson = one(db, 'SELECT id FROM lessons WHERE num = ?', Number(numStr));
  if (!lesson) { console.warn('нет урока', numStr); continue; }

  for (const [kind, difficulty, question, ideal] of data.questions ?? []) {
    const ex = one(db, 'SELECT id FROM questions WHERE lesson_id = ? AND question = ?', lesson.id, question);
    if (ex) run(db, 'UPDATE questions SET kind = ?, difficulty = ?, ideal_answer = ? WHERE id = ?',
                kind, difficulty, ideal, ex.id);
    else {
      run(db, `INSERT INTO questions (lesson_id, kind, difficulty, question, ideal_answer)
               VALUES (?, ?, ?, ?, ?)`, lesson.id, kind, difficulty, question, ideal);
      addedQ++;
    }
  }

  for (const [title, minutes, body] of data.tasks ?? []) {
    const ex = one(db, 'SELECT id FROM tasks WHERE lesson_id = ? AND title = ?', lesson.id, title);
    if (ex) run(db, 'UPDATE tasks SET est_minutes = ?, body = ? WHERE id = ?', minutes, body, ex.id);
    else {
      run(db, 'INSERT INTO tasks (lesson_id, title, est_minutes, body) VALUES (?, ?, ?, ?)',
          lesson.id, title, minutes, body);
      addedT++;
    }
  }

  run(db, 'UPDATE lessons SET content_ready = 1 WHERE id = ?', lesson.id);
}

console.log('вопросов добавлено: %d, задач: %d', addedQ, addedT);
db.close();
